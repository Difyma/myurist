function getIPClause(type) {
  const clauses = {
    exclusive: `3.1. Исключительные права на результат работ (включая исходные коды, макеты, тексты) передаются Заказчику после полной оплаты по настоящему договору.

3.2. До момента передачи прав Исполнитель сохраняет все права на созданные материалы.

3.3. Исполнитель вправе использовать созданные материалы в портфолио после публичного размещения результата работ.`,
    
    license: `3.1. На Заказчика передается простая (неисключительная) лицензия на использование результата работ на территории Российской Федерации.

3.2. Лицензия предоставляется на срок действия исключительных прав (всю жизнь автора плюс 70 лет).

3.3. Авторские права на результат работ остаются у Исполнителя.`,
    
    work_for_hire: `3.1. Результат работ является служебным произведением (п. 2 ст. 1295 ГК РФ).

3.2. Исключительные права на результат работ принадлежат Заказчику с момента создания.

3.3. Исполнитель сохраняет право авторства (право признаваться автором).`
  };
  
  return clauses[type] || clauses.exclusive;
}

function numberToWords(num) {
  const number = parseInt(num);
  if (isNaN(number)) return '...';
  
  const ones = ['', 'один', 'два', 'три', 'четыре', 'пять', 'шесть', 'семь', 'восемь', 'девять'];
  const teens = ['десять', 'одиннадцать', 'двенадцать', 'тринадцать', 'четырнадцать', 'пятнадцать', 'шестнадцать', 'семнадцать', 'восемнадцать', 'девятнадцать'];
  const tens = ['', '', 'двадцать', 'тридцать', 'сорок', 'пятьдесят', 'шестьдесят', 'семьдесят', 'восемьдесят', 'девяносто'];
  const hundreds = ['', 'сто', 'двести', 'триста', 'четыреста', 'пятьсот', 'шестьсот', 'семьсот', 'восемьсот', 'девятьсот'];
  const thousands = ['тысяч', 'тысяча', 'тысячи', 'тысячи', 'тысячи'];
  
  if (number === 0) return 'ноль';
  
  function convert(n) {
    if (n < 10) return ones[n];
    if (n < 20) return teens[n - 10];
    if (n < 100) return tens[Math.floor(n / 10)] + (n % 10 ? ' ' + ones[n % 10] : '');
    if (n < 1000) return hundreds[Math.floor(n / 100)] + (n % 100 ? ' ' + convert(n % 100) : '');
    return '';
  }
  
  if (number < 1000) return convert(number);
  if (number < 1000000) {
    const t = Math.floor(number / 1000);
    const r = number % 1000;
    let tWord = convert(t);
    
    // Special cases for thousands
    if (t === 1) tWord = 'одна тысяча';
    else if (t === 2) tWord = 'две тысячи';
    else if (t >= 3 && t <= 4) tWord = tWord + ' тысячи';
    else tWord = tWord + ' тысяч';
    
    return tWord + (r ? ' ' + convert(r) : '');
  }
  
  return number.toLocaleString('ru-RU');
}
